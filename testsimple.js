// Simple rules, the hidden test mode. node testsimple.js
process.env.PORT = 0;
const assert = require('assert');
const B = require('./game.js');
const T = require('./three.js');
const H = require('./hunt.js');
const TT = require('./team.js');
const S = require('./simple.js');
const server = require('./server.js');
let n = 0;
const ok = (name, f) => { f(); n++; console.log('ok', name); };
const k = p => p[0] + ',' + p[1];

function play2() {
  const g = B.newGame();
  S.arm(g);
  g.phase = 'play'; g.turn = 'blue'; g.round = 1;
  g.ostrich = [2, 2]; g.vulture = [6, 2];
  g.eggs = [{ id: 0, pos: [2, 2], alive: true, lastWarm: 1 }, { id: 1, pos: [4, 5], alive: true, lastWarm: 1 }, { id: 2, pos: [0, 4], alive: true, lastWarm: 1 }];
  return g;
}
function play3(kind = 'hyena') {
  const g = T.newGame3(kind, undefined, [8, 3]);
  S.arm(g);
  g.phase = 'play'; g.turn = 'red'; g.round = 1;
  g.ostrich = [2, 3]; g.vulture = [4, 3]; g.three.h = [8, 3];
  g.eggs = [{ id: 0, pos: [2, 3], alive: true, lastWarm: 1 }, { id: 1, pos: [0, 5], alive: true, lastWarm: 1 }, { id: 2, pos: [1, 1], alive: true, lastWarm: 1 }];
  return g;
}
function room3(simple) {
  const made = server.create3({ role: 'blue', simple: !!simple, bots: ['red', 'hunter'], kind: 'hyena' }, null);
  const g = made.room.g;
  g.phase = 'play'; g.turn = 'red'; g.round = 1;
  g.ostrich = [1, 1]; g.vulture = [4, 1]; g.three.h = [8, 6]; g.three.kind = 'hyena';
  g.eggs = [{ id: 0, pos: [1, 1], alive: true, lastWarm: 1 }, { id: 1, pos: [0, 3], alive: true, lastWarm: 1 }, { id: 2, pos: [2, 5], alive: true, lastWarm: 1 }];
  return made.room;
}

ok('1. everyone sees every animal, and only a camouflaged animal is hidden from opponents', () => {
  const room = room3(true);
  const g = room.g;
  const hunter = server.view3(room, 'hunter');
  const bird = server.view3(room, 'blue');
  assert.deepEqual(hunter.ostrich, [1, 1], 'the hunter sees the ostrich');
  assert.deepEqual(hunter.vulture, [4, 1], 'the hunter sees the vulture');
  assert.deepEqual(bird.h3.hunter, [8, 6], 'a bird sees the hunter across the board');
  assert.ok(B.vultureFly(g, [5, 1]), 'vulture moves');
  g.turn = 'blue';
  assert.ok(B.hideTurn(g, 'blue'));
  const hidHunter = server.view3(room, 'hunter');
  const hidSelf = server.view3(room, 'blue');
  assert.ok(hidHunter.ostrich[0] < 0, 'the hunter does not see a camouflaged ostrich');
  assert.deepEqual(hidSelf.ostrich, g.ostrich, 'the ostrich still sees itself');
  assert.equal(hidSelf.veil.blue, 1, 'its own phone uses the hidden look');
  const team = TT.newTeam(4);
  S.arm(team);
  team.phase = 'play'; team.turn = 'o1'; team.round = 1;
  team.b.o1.pos = [1, 1]; team.b.o2.pos = [1, 3]; team.b.v1.pos = [6, 1]; team.b.v2.pos = [6, 3];
  assert.ok(TT.hideSeat(team, 'o1'));
  assert.equal(S.sees(team, 'o2', 'o1'), true, 'a teammate still sees you');
  assert.equal(S.sees(team, 'v1', 'o1'), false, 'the other side does not');
  const made = server.createT({ team: 4, role: 'o1', simple: true, bots: ['o2', 'v1', 'v2'] }, null);
  const tg = made.room.g;
  tg.phase = 'play'; tg.turn = 'o2'; tg.round = team.round; tg.b.o1.pos = team.b.o1.pos; tg.b.o2.pos = [2, 3]; tg.b.v1.pos = [6, 1]; tg.b.v2.pos = [6, 3];
  S.arm(tg); tg.camo.o1 = { left: 1, until: tg.round };
  const mate = server.viewT(made.room, 'o2');
  const foe = server.viewT(made.room, 'v1');
  assert.ok(mate.h3.pieces.some(p => p.seat === 'o1' && p.camo), 'the teammate phone gets the hidden look');
  assert.ok(!foe.h3.pieces.some(p => p.seat === 'o1'), 'the other side is not sent that animal');
});

ok('2. camouflage: 2 uses, 2 rounds, a bump reveals, a hunter still catches', () => {
  const g = play2();
  g.turn = 'blue';
  assert.equal(S.left(g, 'blue'), 2);
  assert.ok(B.hideTurn(g, 'blue'));
  assert.equal(S.left(g, 'blue'), 1);
  assert.equal(S.hidden(g, 'blue'), true);
  g.turn = 'red'; g.vulture = [4, 2];
  const from = g.vulture.slice();
  assert.ok(B.flyTargets(g).some(p => k(p) === k(g.ostrich)), 'the hidden ostrich square looks open');
  assert.ok(B.vultureFly(g, g.ostrich.slice()));
  assert.deepEqual(g.vulture, from, 'the mover stays put');
  assert.equal(S.hidden(g, 'blue'), false, 'the hidden animal is revealed');
  g.round = 3; g.turn = 'blue';
  assert.ok(B.hideTurn(g, 'blue'));
  assert.equal(S.hidden(g, 'blue'), true, 'hidden in the round it is used');
  g.round = 4;
  assert.equal(S.hidden(g, 'blue'), true, 'still hidden the next round');
  g.round = 5;
  assert.equal(S.hidden(g, 'blue'), false, 'seen again after 2 rounds');
  assert.equal(S.left(g, 'blue'), 0);
  g.turn = 'blue';
  assert.equal(B.hideTurn(g, 'blue'), false, 'no third hide');
  const t = play3();
  t.turn = 'blue'; t.ostrich = [2, 3];
  assert.ok(B.hideTurn(t, 'blue'));
  t.three.h = [3, 3]; t.turn = 'hunter';
  const at = t.ostrich.slice();
  assert.ok(T.hunterMove(t, at.slice()));
  assert.equal(t.three.birds.blue.catches, 1, 'a hunter landing on a hidden bird still catches it');
  assert.equal(S.hidden(t, 'blue'), false);
  assert.equal(B.dist(t.ostrich, at), 3, 'the caught bird is set down 3 squares away');
  t.three.birds.blue.catches = 1; t.turn = 'hunter'; t.three.h = [t.ostrich[0], Math.min(6, t.ostrich[1] + 1)];
  if (B.dist(t.three.h, t.ostrich) > 2) t.three.h = [t.ostrich[0], t.ostrich[1]];
  const spot = t.ostrich.slice();
  t.three.h = [spot[0] + 1, spot[1]];
  if (t.three.h[0] > 8) t.three.h = [spot[0] - 1, spot[1]];
  assert.ok(T.hunterMoves(t).some(p => k(p) === k(spot)));
  assert.ok(T.hunterMove(t, spot));
  assert.equal(t.three.birds.blue.out, true, 'the second catch knocks the bird out');
});

ok('3. no carrying eggs', () => {
  const g = play2();
  g.turn = 'blue';
  assert.equal(B.canCarry(g), false);
  assert.deepEqual(B.ostrichMoves(g, true), []);
  assert.equal(B.ostrichStep(g, [3, 3], true), false);
  assert.equal(g.carrying, null);
  const far = B.ostrichMoves(g).some(p => B.dist(p, g.ostrich) === 2);
  assert.equal(far, true, 'without a carry, the ostrich still walks 2');
  const team = TT.newTeam(4); S.arm(team); team.phase = 'play'; team.turn = 'o1';
  team.b.o1.pos = [2, 2]; team.b.o2.pos = [0, 0]; team.b.v1.pos = [7, 1]; team.b.v2.pos = [7, 5];
  team.eggs = [{ id: 0, nest: 0, pos: [2, 2], alive: true, lastWarm: 1 }];
  assert.equal(TT.canCarry(team, 'o1'), false);
  assert.equal(TT.ostrichAct(team, 'o1', 'carry', [3, 2]), false);
});

ok('4. eggs are found only by landing, with no sniff, and a found egg is shown to everyone', () => {
  const g = play2();
  g.turn = 'red'; g.vulture = [4, 4];
  assert.ok(B.vultureFly(g, [4, 5]));
  assert.equal(g.marks['4,5'], 'spotted', 'landing on the egg finds it');
  assert.equal(g.sniff, null, 'no sniff');
  assert.equal(g.lastAction.smell, false);
  g.turn = 'red'; g.vulture = [2, 4];
  assert.ok(B.vultureFly(g, [2, 4].slice ? [3, 4] : [3, 4]));
  assert.equal(g.sniff, null);
  assert.notEqual(g.lastAction.smell, true, 'standing next to an egg does not sniff');
  const room = room3(true);
  room.g.turn = 'red'; room.g.vulture = [2, 4];
  assert.ok(B.vultureFly(room.g, [2, 5]));
  assert.equal(room.g.marks['2,5'], 'spotted');
  const hunter = server.view3(room, 'hunter');
  assert.equal(hunter.marks['2,5'], 'spotted', 'the hunter is shown the found egg');
  assert.equal(hunter.sniff, null);
  const bird = server.view3(room, 'red');
  assert.equal(bird.sniff, null, 'the vulture gets no Egg nearby hint');
});

ok('5. same moves and goals: 2 squares, no pounce, no double turn, kicks stop, 2 knock outs', () => {
  const g = play3();
  g.turn = 'hunter'; g.vulture = [6, 3];
  g.three.sense = true;
  assert.ok(T.hunterMoves(g).some(p => B.dist(p, g.three.h) === 2), 'the hunter walks 2');
  assert.ok(!T.hunterMoves(g).some(p => B.dist(p, g.three.h) > 2), 'the hunter does not walk 3');
  assert.ok(T.hunterMove(g, [7, 3]));
  assert.equal(g.three.pounce, false, 'no pounce');
  assert.notEqual(g.turn, 'hunter');
  const ko = play3();
  ko.turn = 'hunter'; ko.ostrich = [7, 3]; ko.three.birds.blue.catches = 1;
  assert.ok(T.hunterMove(ko, [7, 3]));
  assert.equal(ko.three.birds.blue.out, true);
  assert.notEqual(ko.turn, 'hunter', 'no hunter double turn');
  const kick = play2();
  kick.turn = 'blue'; kick.ostrich = [4, 4]; kick.vulture = [4, 5];
  assert.ok(B.ostrichKick(kick, [4, 5]));
  assert.deepEqual(kick.vulture, [4, 6], 'the kick stops at the edge');
  const edge3 = play3('badger');
  edge3.turn = 'blue'; edge3.ostrich = [4, 2]; edge3.three.h = [4, 3]; edge3.vulture = [0, 0];
  assert.ok(T.ostrichKick3(edge3, [4, 3]));
  assert.deepEqual(edge3.three.h, [4, 6], 'a badger is kicked 3, the same as every animal');
  const five = TT.newTeam(5, 'hyena'); S.arm(five);
  five.phase = 'play'; five.round = 1; five.turn = 'hunter';
  five.eggs = [{ id: 0, nest: 0, pos: [3, 3], alive: true, lastWarm: 1 }];
  ['o1', 'o2', 'v1', 'v2'].forEach((s, i) => { five.b[s].pos = [i, 0]; });
  TT.knockout(five, 'o1', 'caught');
  assert.equal(five.phase, 'play', 'one knock out is not enough');
  TT.knockout(five, 'o2', 'caught');
  assert.equal(five.winner, 'hunter', 'two knock outs win, even two ostriches');
  assert.equal(five.endWhy, 'The hyena knocked out 2 birds.');
  const hunt = H.newHunt(undefined, [[0, 3], [8, 3]]); S.arm(hunt);
  hunt.phase = 'play'; hunt.turn = 'hyena'; hunt.ostrich = [2, 3]; hunt.vulture = [6, 3];
  hunt.eggs = [{ id: 0, pos: [1, 6], alive: true, lastWarm: 1 }];
  hunt.hunt.hs.hyena.p = [4, 3]; hunt.hunt.hs.badger.p = [5, 3];
  assert.ok(H.hunterMove(hunt, [5, 3]));
  assert.deepEqual(hunt.hunt.hs.hyena.p, [4, 3], 'a hunter that would land on the other stays put');
  assert.deepEqual(hunt.hunt.hs.badger.p, [5, 3]);
  H.knockout(hunt, 'red', 'caught', 'hyena');
  hunt.hunt.hs.badger.catches = 5; hunt.hunt.hs.hyena.catches = 0;
  H.knockout(hunt, 'blue', 'caught', 'badger');
  assert.equal(hunt.winner, 'none', 'equal knock outs tie, catches do not break it');
  assert.ok(/The hunters tie\./.test(hunt.endWhy));
  const ahead = H.newHunt(undefined, [[0, 3], [8, 3]]); S.arm(ahead);
  ahead.phase = 'play'; ahead.ostrich = [2, 3]; ahead.vulture = [6, 3];
  ahead.eggs = [{ id: 0, pos: [1, 6], alive: true, lastWarm: 1 }];
  H.knockout(ahead, 'red', 'caught', 'hyena');
  H.knockout(ahead, 'blue', 'caught', 'hyena');
  assert.equal(ahead.winner, 'hyena');
  assert.ok(/more knock outs/.test(ahead.endWhy));
});

ok('a normal game is unchanged without the flag', () => {
  const made = server.create3({ role: 'blue', bots: ['red', 'hunter'], kind: 'hyena' }, null);
  assert.equal(made.room.simple, undefined);
  assert.equal(made.room.g.simple, undefined);
  const g = B.newGame();
  assert(B.placeEgg(g, [2, 2])); assert(B.placeEgg(g, [6, 2])); assert(B.placeEgg(g, [2, 5]));
  B.placeOstrich(g, [2, 2]);
  assert.ok(B.vultureFly(g, [5, 2]));
  assert.equal(g.lastAction.smell, true, 'a normal landing still sniffs');
  assert.ok(g.sniff);
  assert.equal(B.canCarry(g), true);
  assert.ok(B.ostrichStep(g, [3, 3], true));
  assert.equal(g.carrying, 0, 'a normal ostrich still carries');
  const kick = B.newGame(); kick.phase = 'play'; kick.turn = 'blue'; kick.ostrich = [4, 5]; kick.vulture = [4, 6];
  assert.ok(B.ostrichKick(kick, [4, 6]));
  assert.deepEqual(kick.vulture, [4, 2], 'a normal kick still wraps');
  const t = T.newGame3('hyena', undefined, [0, 3]);
  t.phase = 'play'; t.turn = 'hunter'; t.ostrich = [4, 6]; t.vulture = [2, 4]; t.three.h = [0, 3]; t.three.sense = true;
  assert.ok(T.hunterMove(t, [1, 3]));
  assert.equal(t.three.pounce, true, 'a normal hyena still pounces');
  const b = T.newGame3('badger', undefined, [8, 3]);
  b.phase = 'play'; b.turn = 'hunter'; b.ostrich = [0, 0]; b.vulture = [0, 6];
  assert.ok(T.hunterStay(b));
  assert.equal(b.three.burrowed, true, 'a normal badger still burrows');
  const hunterView = server.view3(made.room, 'hunter');
  made.room.g.phase = 'play'; made.room.g.ostrich = [1, 1]; made.room.g.vulture = [4, 1];
  const hidden = server.view3(made.room, 'hunter');
  assert.ok(hidden.ostrich[0] < 0, 'a normal hunter still does not see the birds');
  assert.equal(hunterView.simple, undefined);
  const five = TT.newTeam(5, 'hyena');
  five.phase = 'play'; five.turn = 'hunter';
  five.eggs = [{ id: 0, nest: 0, pos: [3, 3], alive: true, lastWarm: 1 }];
  ['o1', 'o2', 'v1', 'v2'].forEach((s, i) => { five.b[s].pos = [i, 1]; });
  TT.knockout(five, 'o1', 'caught');
  TT.knockout(five, 'o2', 'caught');
  assert.equal(five.phase, 'play', 'a normal hunter does not win on two ostriches');
});

